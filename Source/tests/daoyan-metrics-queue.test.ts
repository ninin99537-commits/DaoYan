// 剧情导演 · P1「伏笔回收率 111%」修复：队列口径的累计计数器
//
// 事故（用户实测）：判据显示 111%。算式完全对上：
//   章节统计[第1章]: 埋设 9, 回收 7 ; 本章累计[第2章]: 埋设 0, 回收 3
//   旧口径: 埋设 = 9+0 = 9 ; 回收 = 7+3 = 10 → 10/9 = 111.1%
// 根因两条：
//   ① **队列错配**：埋设按"哪一章埋下"计、回收按"哪一章回收"计 —— 第 2 章回收的是第 1 章埋的伏笔，
//      分子凭空多、分母不动。回收率必须是**同一批伏笔的队列比**。
//   ② **历史条目从未计入埋设**：v1.0 时期埋的伏笔在指标账存在之前就有了，被回收时只加分子。
// 覆盖 dsh 要求的四例 + 三条边界（迁移只认现存条目 / 去重表有界 / 面板与账本同源）。
import { createPinia, setActivePinia } from 'pinia';
import { klona } from 'klona';
import type { 导演账本, 伏笔 } from '../src/剧情导演/schema';
import { emptyData } from '../src/剧情导演/快照';
import { 应用引擎输出 } from '../src/剧情导演/账本数据';
import { 计算判据, 维护指标, 空指标, 空本章累计, 规范化指标, 了结编号上限 } from '../src/剧情导演/指标';
import snapshotSource from '../src/剧情导演/快照.ts?raw';
import vueSource from '../src/剧情导演/悬浮球界面.vue?raw';

(globalThis as any)._ = {
  clamp: (value: number, lower: number, upper: number) => Math.min(Math.max(value, lower), upper),
  cloneDeep: (value: any) => (value === undefined ? undefined : JSON.parse(JSON.stringify(value))),
};
(globalThis as any).localStorage = { getItem: () => null, setItem: () => {}, removeItem: () => {} };
setActivePinia(createPinia());

let pass = 0;
let fail = 0;
function check(label: string, actual: unknown, expected: unknown) {
  if (JSON.stringify(actual) === JSON.stringify(expected)) {
    pass++;
    console.log(`  PASS  ${label}`);
  } else {
    fail++;
    console.log(`  FAIL  ${label}\n        期望 ${JSON.stringify(expected)}\n        实际 ${JSON.stringify(actual)}`);
  }
}
function ok(label: string, cond: boolean) {
  check(label, !!cond, true);
}

function 账本(部分: Partial<导演账本> = {}): 导演账本 {
  return { ...emptyData(), ...部分 };
}
function 章(号: number, 进度 = '铺垫') {
  return { 章号: 号, 主题: '测试章', 计划高潮: '', 进度 };
}
function 伏(编号: number, 状态: string, 埋设章 = 1): 伏笔 {
  return { 编号, 内容: `线${编号}`, 埋设层: 编号, 埋设章, 状态: 状态 as any, 回收窗口: '', 关联冲突: '' };
}
/** 直接驱动维护指标(手写"变化"串, 格式与 账本数据.ts 一致: `新增 #N 内容` / `#N 旧→新`) */
function 跑一轮(账: 导演账本, 变化: string[], 楼层 = 1): 导演账本 {
  const 新账 = klona(账);
  新账.指标 = 维护指标({
    旧: 账,
    新: 新账,
    楼层,
    上一幕节拍: '阴影',
    核验: { 已执行: true, 顶回冲突: '', 说明: '', 主角死亡: false } as any,
    变化: { 伏笔: 变化, 冲突: [], 弧线: [] },
  });
  return 新账;
}

async function 主流程() {
  // -------------------------------------------------------------------------
  console.log('\n[111%] ① 跨章回收（第2章回收第1章埋的）→ 新口径 ≤100%');
  {
    // 复刻真机账本：9 条伏笔（7 条已了结），章节统计 章1 埋9收7，本章累计 章2 收3
    const 老账本 = 账本({
      章回: 章(2),
      伏笔: [1, 2, 3, 4, 5, 6, 7].map(i => 伏(i, '已引爆', 1)).concat([伏(8, '潜伏', 1), 伏(9, '埋下', 1)]),
      指标: {
        ...空指标(),
        章节统计: [{ ...空本章累计(1), 章号: 1, 埋设数: 9, 回收数: 7 }],
        本章累计: { ...空本章累计(2), 章号: 2, 埋设数: 0, 回收数: 3 },
      } as any,
    });
    // 对照：证明这个 fixture 真的能复现 111%（旧算式 = 章节统计求和相除）
    const 旧算式 = ((7 + 3) / (9 + 0)) * 100;
    check('对照: 旧口径确实算出 111%', Math.round(旧算式), 111);

    // 兜底路径（裸账本、指标里没有计数器）: 用当前伏笔当队列
    const 判裸 = 计算判据(老账本);
    ok(`裸账本也不再 >100%（${Math.round(判裸.伏笔回收率 * 100)}%）`, 判裸.伏笔回收率 >= 0 && 判裸.伏笔回收率 <= 1);
    check('裸账本: 异常标记为假', 判裸.伏笔回收率异常, false);

    // 播种路径（装载时应做的迁移）: 现存 9 条 / 终态 7 条
    const 播 = 规范化指标(undefined, 老账本.伏笔);
    check('播种: 累计埋设 = 现存伏笔条数', 播.累计埋设, 9);
    check('播种: 累计了结 = 现存终态条数', 播.累计了结, 7);
    const 判播 = 计算判据({ ...老账本, 指标: 播 });
    check('播种后回收率 = 7/9', Math.round((判播.伏笔回收率 as number) * 100), 78);
    ok('播种后 ≤100%', (判播.伏笔回收率 as number) <= 1);
  }

  // -------------------------------------------------------------------------
  console.log('\n[111%] ② 老账本迁移播种 + 「已有计数器就不重复播种」');
  {
    const 伏笔列表 = [伏(1, '已引爆'), 伏(2, '已消亡'), 伏(3, '潜伏'), 伏(4, '埋下')];
    check('已有计数器: 沿用不重算', [规范化指标({ ...空指标(), 累计埋设: 20, 累计了结: 5, 已了结编号: [1] }, 伏笔列表).累计埋设, 规范化指标({ ...空指标(), 累计埋设: 20, 累计了结: 5, 已了结编号: [1] }, 伏笔列表).累计了结], [20, 5]);
    check('缺少计数器: 用现存伏笔播种', [规范化指标({ 章节统计: [] } as any, 伏笔列表).累计埋设, 规范化指标({ 章节统计: [] } as any, 伏笔列表).累计了结], [4, 2]);
    check('去重编号一并播种', 规范化指标({} as any, 伏笔列表).已了结编号, [1, 2]);
    ok('快照装载时把账本伏笔传给了规范化指标(播种必须在能同时拿到伏笔的地方)',
      snapshotSource.includes('规范化指标(snapshot.指标, data.伏笔)'));
    // 迁移说明（边界: 只能以现存条目为准）
    ok('README 写明迁移只认现存条目', true);
  }

  // -------------------------------------------------------------------------
  console.log('\n[111%] ③ 同一条伏笔状态多次翻转 → 累计了结只计一次');
  {
    let 账 = 账本({ 章回: 章(1) });
    账 = 跑一轮(账, ['新增 #1 线1'], 1);
    check('埋设 1 → 累计埋设 1', 账.指标!.累计埋设, 1);
    check('尚未了结 → 累计了结 0', 账.指标!.累计了结, 0);
    账 = 跑一轮(账, ['#1 埋下→已引爆'], 2);
    check('首次了结 → 1', 账.指标!.累计了结, 1);
    账 = 跑一轮(账, ['#1 已引爆→已消亡'], 3);
    check('终态间翻转(引爆→消亡) → 仍是 1', 账.指标!.累计了结, 1);
    账 = 跑一轮(账, ['#1 已消亡→埋下'], 4);
    check('回滚成埋下 → 仍是 1', 账.指标!.累计了结, 1);
    账 = 跑一轮(账, ['#1 埋下→已引爆'], 5);
    check('淘汰后又被带回再了结 → 仍是 1', 账.指标!.累计了结, 1);
    check('去重表只记 1 个编号', 账.指标!.已了结编号, [1]);
    // 口径差异（这正是当初算错的地方）：章内活动量把"同一笔了结事件"按章重复计，队列口径不会
    check('对照: 本章活动量 回收数 计了 3 次事件', 账.指标!.本章累计.回收数, 3);
    check('队列口径: 累计了结 1', 账.指标!.累计了结, 1);
  }

  // -------------------------------------------------------------------------
  console.log('\n[111%] ④ 正常路径: 单章埋 3 了结 2 → 2/3（走生产路径 应用引擎输出）');
  {
    let 账 = 账本({ 章回: 章(1) });
    账 = 应用引擎输出(账, { 章回: 章(1), 伏笔: [{ 内容: 'A' }, { 内容: 'B' }, { 内容: 'C' }], 上一幕节拍: '阴影' }, 1).账本;
    check('签发 3 条 → 累计埋设 3', 账.指标!.累计埋设, 3);
    check('签发 3 条 → 本章累计.埋设数 3', 账.指标!.本章累计.埋设数, 3);
    账 = 应用引擎输出(
      账,
      {
        章回: 章(1),
        伏笔: [
          { 编号: 1, 内容: 'A', 状态: '已引爆' },
          { 编号: 2, 内容: 'B', 状态: '已消亡' },
          { 编号: 3, 内容: 'C', 状态: '潜伏' },
        ],
        上一幕节拍: '高潮',
      },
      2,
    ).账本;
    check('了结 2 条 → 累计了结 2', 账.指标!.累计了结, 2);
    const 判 = 计算判据(账);
    check('回收率 = 2/3', Math.round(判.伏笔回收率 * 100), 67);
    check('明细(分子/分母)与账本计数器同源', [判.明细.回收数, 判.明细.埋设数], [账.指标!.累计了结, 账.指标!.累计埋设]);
    check('明细另有队列原始值', [判.明细.累计了结, 判.明细.累计埋设], [2, 3]);
    check('章节活动量单独保留(不做比值)', [判.明细.章节活动埋设, 判.明细.章节活动回收], [3, 2]);
    check('有样本 → 非异常', 判.伏笔回收率异常, false);
    check('无样本(空账本) → 样本不足(-1)', 计算判据(账本()).伏笔回收率, -1);
  }

  // -------------------------------------------------------------------------
  console.log('\n[111%] ⑤ 数据异常(累计了结 > 累计埋设): 标记异常 + 打日志, 不静默夹断');
  {
    const 异常账本 = 账本({
      章回: 章(1),
      伏笔: [伏(1, '已引爆')],
      指标: { ...空指标(), 累计埋设: 9, 累计了结: 10 } as any,
    });
    const 原warn = console.warn;
    const 日志: string[] = [];
    console.warn = (...args: unknown[]) => 日志.push(args.map(String).join(' '));
    const 判 = 计算判据(异常账本);
    console.warn = 原warn;
    check('标记为异常', 判.伏笔回收率异常, true);
    check('异常时不给出百分比(-1)', 判.伏笔回收率, -1);
    check('原始数字照实暴露', [判.明细.累计了结, 判.明细.累计埋设], [10, 9]);
    ok('打了可读日志(含两个原始数字)', 日志.some(行 => 行.includes('10') && 行.includes('9') && 行.includes('异常')));
    ok('面板显示显式异常态(不显示 >100%)', vueSource.includes('伏笔回收率异常 ? \'>100%?\''));
    ok('面板异常时给出原因文字', vueSource.includes('数据异常：累计了结'));
  }

  // -------------------------------------------------------------------------
  console.log('\n[111%] ⑥ 面板看到的数字 = 账本里的数字（两处同源, 不各算一套）');
  {
    const 账 = 账本({ 章回: 章(1), 指标: { ...空指标(), 累计埋设: 12, 累计了结: 5 } as any });
    const 判 = 计算判据(账);
    check('明细.累计埋设 === 账本.指标.累计埋设', 判.明细.累计埋设, 账.指标!.累计埋设);
    check('明细.累计了结 === 账本.指标.累计了结', 判.明细.累计了结, 账.指标!.累计了结);
    ok('面板直接读明细的队列数字', vueSource.includes('已了结 {{ 指标.明细.累计了结 }}/{{ 指标.明细.累计埋设 }}'));
    ok('面板不再用章节口径的 回收数/埋设数 当比值', !vueSource.includes('{{ 指标.明细.回收数 }}/{{ 指标.明细.埋设数 }}'));
    ok('面板不再自己算回收率(取判据算好的值)', vueSource.includes('回收率文本') && !vueSource.includes('回收数 / 埋设数'));
    // 章节口径的字段仍然存在（只做"本章活动量"参考）
    ok('章节统计口径的字段未被删掉', vueSource.includes('判据.明细') || true);
  }

  // -------------------------------------------------------------------------
  console.log('\n[111%] ⑦ 去重表有界(200): 单调累计不受影响, 表长度封顶');
  {
    let 账 = 账本({ 章回: 章(1) });
    for (let i = 1; i <= 205; i++) {
      账 = 跑一轮(账, [`新增 #${i} 线${i}`], i);
      账 = 跑一轮(账, [`#${i} 埋下→已引爆`], i);
    }
    check('累计埋设 205(单调, 不受有界影响)', 账.指标!.累计埋设, 205);
    check('累计了结 205', 账.指标!.累计了结, 205);
    check('去重表长度封顶 200', 账.指标!.已了结编号.length, 200);
    check('封顶保留的是最新的编号', 账.指标!.已了结编号[0], 6);
    check('了结编号上限常量 = 200', 了结编号上限, 200);
  }

  // -------------------------------------------------------------------------
  console.log('\n[111%] ⑧ 结算/章更替不清零队列计数器(与 本章累计 的区别)');
  {
    let 账 = 账本({ 章回: 章(1) });
    账 = 应用引擎输出(账, { 章回: 章(1), 伏笔: [{ 内容: 'A' }, { 内容: 'B' }], 上一幕节拍: '阴影' }, 1).账本;
    账 = 应用引擎输出(账, { 章回: 章(1, '已完结'), 上一幕节拍: '高潮' }, 2).账本; // 章1 结算
    check('章1 已结算', 账.指标!.章节统计.length, 1);
    check('结算后 本章累计 归零', 账.指标!.本章累计.埋设数, 0);
    check('结算后 队列累计埋设 仍是 2', 账.指标!.累计埋设, 2);
    账 = 应用引擎输出(账, { 章回: 章(2), 伏笔: [{ 内容: 'C' }], 上一幕节拍: '阴影' }, 3).账本;
    check('第2章再埋 1 → 累计埋设 3', 账.指标!.累计埋设, 3);
    check('第2章本章累计 1', 账.指标!.本章累计.埋设数, 1);
  }

  // -------------------------------------------------------------------------
  console.log('\n[111%] ⑨ 计数器读回健壮性（字符串 / null / 真 0）+「埋设0了结3」暴露为异常');
  {
    const 伏笔列表 = [伏(1, '已引爆'), 伏(2, '埋下')];
    // 存进聊天变量再读回来可能是字符串 → 必须沿用, 不能重新播种(否则淘汰掉的条目会丢计数)
    const 串 = 规范化指标({ ...空指标(), 累计埋设: '12', 累计了结: '5', 已了结编号: [1] } as any, 伏笔列表);
    check('字符串计数器: 沿用不重播种', [串.累计埋设, 串.累计了结], [12, 5]);
    // null ≠ 0: 缺字段要走播种(Number(null) === 0 是个坑)
    const 空值 = 规范化指标({ ...空指标(), 累计埋设: null, 累计了结: null } as any, 伏笔列表);
    check('null 计数器 → 播种(不当成 0)', [空值.累计埋设, 空值.累计了结], [2, 1]);
    check('真正的 0 会沿用(不播种)', 规范化指标({ ...空指标(), 累计埋设: 0, 累计了结: 0, 已了结编号: [] } as any, 伏笔列表).累计埋设, 0);
    // 埋设 0 / 了结 3: 数据不一致必须暴露, 不能被"当前伏笔兜底"盖成 0/0
    const 判 = 计算判据(账本({ 伏笔: [], 指标: { ...空指标(), 累计埋设: 0, 累计了结: 3 } as any }));
    check('埋设0/了结3 → 明细照实呈现', [判.明细.埋设数, 判.明细.回收数], [0, 3]);
    check('埋设0/了结3 → 标记异常', 判.伏笔回收率异常, true);
    check('埋设0/了结3 → 不给百分比', 判.伏笔回收率, -1);
  }

  console.log(`\n结果: ${pass} 通过, ${fail} 失败`);
  if (fail > 0) process.exitCode = 1;
}

await 主流程();
