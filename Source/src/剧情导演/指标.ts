// 剧情导演 · 指标账: 让「跌宕起伏」可度量的可算数据(§3 五项判据的落地)。
//
// 三条纪律:
//  1. **零 AI 负担** —— 所有字段由代码维护, 提示词从不要求 AI 输出它们(改提示词的人才破坏这条);
//  2. **只在写入端裁切** —— 章节统计有界 20 章、节拍/张力历史有界 40 条; 读取端零截断;
//  3. **纯函数** —— 不碰平台、不碰 Vue, 可脱离酒馆单测。
//
// 为什么需要「本章累计」: 章节统计要在章末一次性结算(章号/埋设数/回收数/峰谷/起伏/推进/受挫),
// 而判据要的是**整章**的聚合值, 不是最近 40 轮的窗口。所以进行中的那一章单独攒一个累计器,
// 结算时整条落进 章节统计, 然后把累计器重置为下一章。
//
// 为什么需要「累计埋设/累计了结」(P1: 回收率曾算出 111%):
//   章节统计的口径是"**哪一章**埋下 / **哪一章**了结"——第 2 章回收第 1 章埋的伏笔时,
//   分子凭空多、分母不动, 求和再相除必然 >100%。**回收率必须是同一批伏笔的队列比**,
//   所以另立一对**单调递增、按编号去重**的累计计数器, 只做比值用。
import { klona } from 'klona';
import type { 导演账本, 指标账, 章节统计, 节拍, 判据, 伏笔 } from './schema';
import type { 核验结果 } from './引擎规则';

/** 章节统计有界: 最近 20 章 */
export const 章节统计上限 = 20;
/** 节拍/张力历史有界: 最近 40 轮 */
export const 历史上限 = 40;
/**
 * "已了结编号"去重表的有界值: 只为"同一条伏笔永不重复计了结"服务, 不需要无限长
 * (最旧的按数量淘汰; 200 条编号约 1KB, 远小于账本本身)。
 * **已知边界(dsh 2026-10-07 认可"写清楚即可")**: 若某个编号滑出这 200 的窗口后, 同一条伏笔
 * 又发生一次"→已引爆/已消亡"翻转, 理论上会**重复计一次**。实际伏笔总量远小于 200, 不为此加复杂度。
 */
export const 了结编号上限 = 200;
/**
 * "还没观测到张力"的哨兵值。
 * 张力合法区间是 0..10, 所以 -1 不会与真实值撞车 —— 用 0 冒充"未观测"会让每一章的"张力谷"被初值污染成 0。
 */
export const 未观测张力 = -1;

/** 空累计器(章号 0 = 尚无章回)。峰谷默认"未观测"(-1), 只由本章实际轮次填。 */
export function 空本章累计(章号 = 0, 张力: number = 未观测张力): 章节统计 {
  return {
    章号,
    埋设数: 0,
    回收数: 0,
    张力峰: 张力,
    张力谷: 张力,
    起伏次数: 0,
    冲突推进数: 0,
    受挫数: 0,
  };
}

export function 空指标(): 指标账 {
  return {
    章节统计: [],
    节拍历史: [],
    张力历史: [],
    核验: { 总: 0, 未执行: 0 },
    本章累计: 空本章累计(),
    累计埋设: 0,
    累计了结: 0,
    已了结编号: [],
    终值: null,
  };
}

/** 有界追加: 只在**写入端**裁切, 保留最新的 上限 条 */
function 有界追加<T>(列表: T[], 项: T, 上限: number): T[] {
  const out = [...列表, 项];
  return out.length > 上限 ? out.slice(out.length - 上限) : out;
}

/** 张力方向(相邻两值): 用于统计"起伏次数"——方向反转才算一次起伏 */
function 方向(前: number, 后: number): number {
  return 后 > 前 ? 1 : 后 < 前 ? -1 : 0;
}

/** 宽松取数: 数字/数字字符串都收, 其余给兜底 */
function 取数(value: unknown, 兜底 = 0): number {
  if (typeof value === 'number') return Number.isFinite(value) ? value : 兜底;
  if (typeof value === 'string' && value.trim() !== '') {
    const n = Number(value);
    return Number.isFinite(n) ? n : 兜底;
  }
  return 兜底;
}

/**
 * 读一个**累计计数器**(累计埋设/累计了结): 数字与数字字符串都收(存进聊天变量再读回来的可能是字符串),
 * 读不出(缺字段 / null / 空串 / 非数字) → `null`, 交给调用方走"用现存伏笔播种"。
 * 注意 `Number(null) === 0` 这种坑: 必须把 null/undefined/'' 和真正的 0 区分开, 否则会把老账本当成"计数为 0"。
 */
function 读计数器(值: unknown): number | null {
  if (值 === null || 值 === undefined || 值 === '') return null;
  const n = Number(值);
  return Number.isFinite(n) ? Math.max(0, Math.round(n)) : null;
}

/** 伏笔是否已了结(引爆或明确消亡都算) */
function 是了结状态(状态: unknown): boolean {
  return 状态 === '已引爆' || 状态 === '已消亡';
}

/** 从变化串里取伏笔编号: `#3 埋设→已引爆` / `新增 #5 内容` */
function 解析伏笔编号(项: string): number | null {
  const 匹配 = /#(\d+)/.exec(String(项));
  if (!匹配) return null;
  const 编号 = Number(匹配[1]);
  return Number.isFinite(编号) && 编号 > 0 ? 编号 : null;
}

/** 老账本播种/去重表的统一入口: 现有终态伏笔的编号(有界) */
function 终态编号(伏笔列表: 伏笔[]): number[] {
  return 伏笔列表
    .filter(项 => 是了结状态(项?.状态))
    .map(项 => 取数(项?.编号))
    .filter(编号 => 编号 > 0)
    .slice(-了结编号上限);
}

/**
 * 把一份(可能来自旧账本或坏数据)的指标账补齐成当前结构 —— 老账本迁移: 默认填充, 不清空不崩。
 * `账本伏笔` 用于**播种队列计数器**(见上): 老账本没有 `累计埋设/累计了结`, 而 v1.0 时期埋下的伏笔
 * 在指标账存在**之前**就有了 —— 不给它们补记"埋设", 一回收就只剩分子, 回收率必然虚高。
 */
export function 规范化指标(raw: any, 账本伏笔: 伏笔[] = []): 指标账 {
  const 指标 = 空指标();
  if (!raw || typeof raw !== 'object') {
    // 连指标账都没有(老账本 / 全新账本) → 直接用账本里的伏笔播种
    指标.累计埋设 = 账本伏笔.length;
    指标.累计了结 = 终态编号(账本伏笔).length;
    指标.已了结编号 = 终态编号(账本伏笔);
    return 指标;
  }
  if (Array.isArray(raw.章节统计)) {
    指标.章节统计 = raw.章节统计.filter((项: any) => 项 && typeof 项 === 'object').map((项: any) => ({
      ...空本章累计(取数(项.章号)),
      章号: 取数(项.章号),
      埋设数: 取数(项.埋设数),
      回收数: 取数(项.回收数),
      张力峰: 取数(项.张力峰, 未观测张力),
      张力谷: 取数(项.张力谷, 未观测张力),
      起伏次数: 取数(项.起伏次数),
      冲突推进数: 取数(项.冲突推进数),
      受挫数: 取数(项.受挫数),
    }));
  }
  if (Array.isArray(raw.节拍历史)) {
    指标.节拍历史 = raw.节拍历史
      .filter((项: any) => 项 && typeof 项 === 'object')
      .map((项: any) => ({ 楼层: 取数(项.楼层), 节拍: 项.节拍 as 节拍 }));
  }
  if (Array.isArray(raw.张力历史)) {
    指标.张力历史 = raw.张力历史
      .filter((项: any) => 项 && typeof 项 === 'object')
      .map((项: any) => ({ 楼层: 取数(项.楼层), 值: 取数(项.值) }));
  }
  if (raw.核验 && typeof raw.核验 === 'object') {
    指标.核验 = { 总: 取数(raw.核验.总), 未执行: 取数(raw.核验.未执行) };
  }
  if (raw.本章累计 && typeof raw.本章累计 === 'object') {
    指标.本章累计 = {
      ...空本章累计(取数(raw.本章累计.章号)),
      章号: 取数(raw.本章累计.章号),
      埋设数: 取数(raw.本章累计.埋设数),
      回收数: 取数(raw.本章累计.回收数),
      张力峰: 取数(raw.本章累计.张力峰, 未观测张力),
      张力谷: 取数(raw.本章累计.张力谷, 未观测张力),
      起伏次数: 取数(raw.本章累计.起伏次数),
      冲突推进数: 取数(raw.本章累计.冲突推进数),
      受挫数: 取数(raw.本章累计.受挫数),
    };
  }
  // 队列计数器: **有就沿用, 没有才播种**(不能每次都用伏笔重算, 否则淘汰掉的伏笔会丢计数)
  const 读过埋设 = 读计数器(raw.累计埋设);
  const 读过了结 = 读计数器(raw.累计了结);
  指标.累计埋设 = 读过埋设 ?? 账本伏笔.length;
  指标.累计了结 = 读过了结 ?? 终态编号(账本伏笔).length;
  if (Array.isArray(raw.已了结编号)) {
    指标.已了结编号 = raw.已了结编号
      .map((项: any) => 取数(项))
      .filter((编号: number) => 编号 > 0)
      .slice(-了结编号上限);
  } else {
    指标.已了结编号 = 终态编号(账本伏笔);
  }
  // 剧终快照: 老账本没有这个字段 → 保持 null(不崩、不伪造成绩单)
  // 只认"看起来像判据快照"的对象(至少带 `明细`): 半截值(如 {})进来会让结算卡读到 undefined 直接炸,
  // 宁可当没有(结算卡不显示), 也不让一块坏数据把账本页拖垮。
  if (raw.终值 && typeof raw.终值 === 'object' && raw.终值.明细) 指标.终值 = raw.终值 as any;
  return 指标;
}

export interface 维护输入 {
  /** 应用引擎输出**之前**的账本(上一轮结果) */
  旧: 导演账本;
  /** 应用引擎输出**之后**的账本(本轮结果: 章回/伏笔/冲突/张力已是新值) */
  新: 导演账本;
  /** 本轮分析的锚点楼层 */
  楼层: number;
  /** 刚演完的那一幕的节拍(引擎归类) */
  上一幕节拍: 节拍;
  核验: 核验结果;
  变化: { 伏笔: string[]; 冲突: string[]; 弧线: string[] };
}

/**
 * 维护指标账(每轮引擎推进后调用一次):
 * 累计本轮 → 张力峰谷/起伏 → 追加历史 → 核验累计 → 章节结算(幂等) → 章号滚动则重置累计器。
 *
 * 章节结算的**触发面**取"章回发生更替", 两种都算(dsh 2026-10-07 指出的实现要点):
 *  - 进度 由非「已完结」→「已完结」; 或
 *  - 章号变化(引擎直接跳章, 没把旧章标完结) —— 否则旧章的统计永远结算不出来, 判据 1/3 直接失真。
 * 幂等靠"同一章号只结算一次"保证(重 roll / 删楼回退重推都不会重复计账)。
 */
export function 维护指标(输入: 维护输入): 指标账 {
  const { 旧, 新, 楼层, 上一幕节拍, 核验, 变化 } = 输入;
  // 峰谷不拿"入章前的张力"当种子: 它只由本章实际轮次产生(否则每章谷值都会被章外值污染)
  // 第二参 = 旧账本的伏笔: 老账本(没有队列计数器)时用它播种
  const 指标 = 规范化指标(klona(旧?.指标), Array.isArray(旧?.伏笔) ? 旧.伏笔 : []);

  const 旧章号 = 取数(旧?.章回?.章号);
  const 新章号 = 取数(新?.章回?.章号);
  const 已结算过 = (章号: number) => 指标.章节统计.some(项 => 取数(项.章号) === 章号);

  // 归一: 累计器若指向**已结算**的章(结算后又被认领, 或删楼回退把它推回旧章), 就降级成
  // "待开新章"桶 —— 计数留着, 等新章开时并入。没有这一步, 这些事件会挂在已结算的章上, 永远入不了账。
  if (取数(指标.本章累计.章号) > 0 && 已结算过(取数(指标.本章累计.章号))) 指标.本章累计.章号 = 0;

  // 归属: 累计器 = "本轮事件该记到哪一章"
  if (累计指向需重建(指标.本章累计, 旧章号)) {
    指标.本章累计 = 空本章累计(旧章号);
  } else if (取数(指标.本章累计.章号) === 0 && 旧章号 > 0 && !已结算过(旧章号)) {
    // 累计器是空的(全新账本 / 老账本迁移)而旧账本已有**尚未结算**的章 → 认领它。
    // 注意"未结算"这个限定: 已结算的章不认领, 否则结算后的事件会记回已结算的章里, 最后被丢掉。
    指标.本章累计.章号 = 旧章号;
  }
  const 累计 = 指标.本章累计;

  // 1. 本轮累计(纯加法) + 队列口径的累计计数器(只做比值, 不参与章节结算)
  const 新增伏笔数 = 变化.伏笔.filter(项 => 项.startsWith('新增')).length;
  累计.埋设数 += 新增伏笔数;
  指标.累计埋设 += 新增伏笔数;
  // 回收口径 = **已了结**: 引爆或明确消亡都算(设计上"允许自然消亡、不硬造", 只计引爆会系统性低估回收率)
  const 了结项 = 变化.伏笔.filter(项 => 项.includes('→已引爆') || 项.includes('→已消亡'));
  累计.回收数 += 了结项.length;
  for (const 项 of 了结项) {
    const 编号 = 解析伏笔编号(项);
    // 拿不到编号 / 已计过 → 不进队列了结。宁可少计, 不可虚高(同一条伏笔永不重复计:
    // 状态翻转多次、被淘汰后又被引擎当新条带回, 都只算一次)。
    if (编号 === null || 指标.已了结编号.includes(编号)) continue;
    指标.已了结编号 = [...指标.已了结编号, 编号].slice(-了结编号上限);
    指标.累计了结 += 1;
  }
  累计.冲突推进数 += 变化.冲突.filter(项 => !项.startsWith('新增') && 项.includes('→')).length;
  if (上一幕节拍 === '受挫') 累计.受挫数 += 1;

  // 2. 张力峰谷与起伏(起伏 = 方向反转)。峰谷只由本章实际轮次产生: 未观测(-1)时取首值。
  const 张力 = 取数(新?.张力?.当前);
  if (取数(累计.张力峰, 未观测张力) < 0 || 张力 > 取数(累计.张力峰, 未观测张力)) 累计.张力峰 = 张力;
  if (取数(累计.张力谷, 未观测张力) < 0 || 张力 < 取数(累计.张力谷, 未观测张力)) 累计.张力谷 = 张力;
  const 序列 = [...指标.张力历史.map(项 => 取数(项.值)), 张力];
  if (序列.length >= 3) {
    const 前一方向 = 方向(序列[序列.length - 3], 序列[序列.length - 2]);
    const 后一方向 = 方向(序列[序列.length - 2], 序列[序列.length - 1]);
    if (前一方向 !== 0 && 后一方向 !== 0 && 前一方向 !== 后一方向) 累计.起伏次数 += 1;
  }

  // 3. 历史(有界 40, 只在写入端裁切)
  指标.节拍历史 = 有界追加(指标.节拍历史, { 楼层, 节拍: 上一幕节拍 }, 历史上限);
  指标.张力历史 = 有界追加(指标.张力历史, { 楼层, 值: 张力 }, 历史上限);

  // 4. 执行核验累计: 只在"真有上一幕指令"时计数(冷启动那几轮没有指令可核验, 不该虚增分母;
  //    且"缺省视为已执行"的语义不动, 否则执行率虚高)
  if (旧?.当前指令 && !旧.当前指令.已跳过) {
    指标.核验 = {
      总: 取数(指标.核验.总) + 1,
      未执行: 取数(指标.核验.未执行) + (核验.已执行 ? 0 : 1),
    };
  }

  // 5. 章节结算(幂等) + 结算后切到"待开新章"桶
  //    触发面两种: 进度 →「已完结」, 或 **章号前进**(引擎直接跳章)。新章号为 0(引擎本轮没给章回)不结算,
  //    免得一个缺字段的载荷把进行中的章误判成已结算。
  const 章已完结 = 旧?.章回?.进度 === '已完结' || 新?.章回?.进度 === '已完结';
  const 章滚动 = 新章号 > 0 && 累计.章号 > 0 && 新章号 !== 累计.章号;
  const 该结算 = (章滚动 || 章已完结) && 累计.章号 > 0 && !已结算过(累计.章号);
  if (该结算) {
    指标.章节统计 = 有界追加(指标.章节统计, klona(累计), 章节统计上限);
    // 结算后切到"待开新章"桶: 后续空窗轮(章已完结、引擎还没开新章)的事件先攒在 0 桶, 新章开了补章号并入。
    // 这个"切桶"必须和"入账"同条件 —— 章已结算还反复切桶, 会把空窗轮的事件清掉(F3)。
    指标.本章累计 = 空本章累计(0);
  }
  // 新章已开 → 给"待开新章"桶补章号(空窗轮的事件并入新章, 不丢);
  // 但"新章"若就是刚结算的那一章(引擎只是还挂着它), 不补 —— 否则事件又记回已结算的章里。
  if (新章号 > 0 && 取数(指标.本章累计.章号) === 0 && !已结算过(新章号)) 指标.本章累计.章号 = 新章号;

  return 指标;
}

/** 累计器是否与旧账本的章对不上(引擎跳章/回退): 
 *  章号 0 表示"待开新章"(保留累积不清); 旧账本轮没有章回(旧章号 0)也不重建 —— 
 *  一个缺字段的载荷不该把进行中的章累计清掉。 */
function 累计指向需重建(累计: 章节统计, 旧章号: number): boolean {
  return 取数(累计?.章号) > 0 && 旧章号 > 0 && 取数(累计?.章号) !== 旧章号;
}

/**
 * 成绩单的一行文本(规格 B3 + dsh 补充): 剧终时除了写进 `指标.终值`, **也写一行进日志页** ——
 * 这样即便日后「清除已剧终」把 `终值` 清空, 用户仍能在日志里回看"落幕那一刻的数字"。
 * 只格式化, 不重新计算(数字全部来自传入的 判据)。
 */
export function 终值日志行(终值: 判据 | null | undefined): string {
  if (!终值) return '全书结算：无判据快照';
  const 百分比文本 = (v: number) => (v < 0 ? '样本不足' : `${Math.round(v * 100)}%`);
  const 峰谷 = (v: number) => (v < 0 ? '—' : String(v));
  return [
    '全书结算：',
    `已结算 ${终值.明细.已结算章数} 章`,
    `伏笔回收 ${终值.明细.回收数}/${终值.明细.埋设数}=${终值.伏笔回收率异常 ? '>100%?' : 百分比文本(终值.伏笔回收率)}`,
    `张力峰 ${峰谷(终值.张力峰)}/谷 ${峰谷(终值.张力谷)} · 起伏 ${终值.起伏次数} 次`,
    `冲突推进 ${终值.冲突推进数} · 受挫 ${终值.受挫次数}`,
    `指令执行率 ${百分比文本(终值.指令执行率)}(${终值.明细.核验总} 次核验)`,
  ].join(' · ');
}

/**
 * §3 五项判据(只读指标账, 不改任何行为):
 * 伏笔回收率 / 张力波形与峰谷 / 冲突推进数 / 受挫次数 / 指令执行率。
 * 无样本时给 -1(面板显示「样本不足」), 不用 0 冒充"回收率 0%"。
 *
 * **伏笔回收率(队列口径, 修 111%)**: `累计了结 / 累计埋设` —— 同一批伏笔的队列比。
 * 绝不拿 章节统计 的 埋设/回收 求和做比值(那是"第 2 章回收第 1 章埋的"式错配, 会算出 >100%)。
 * 若数据异常(了结 > 埋设): **不静默夹断** —— 置 `伏笔回收率异常`, 打日志, 面板显示显式异常态。
 */
export function 计算判据(账本: 导演账本 | null | undefined): 判据 {
  const 指标 = 账本?.指标;
  const 章节统计 = Array.isArray(指标?.章节统计) ? 指标!.章节统计 : [];
  const 累计 = 指标?.本章累计;
  const 求和 = (取: (项: 章节统计) => number) => 章节统计.reduce((s, 项) => s + 取数(取(项)), 0);

  const 当前伏笔 = Array.isArray(账本?.伏笔) ? 账本!.伏笔 : [];
  // 队列口径优先; 没有指标账的裸账本用"当前伏笔"兜底(分子分母同源, 所以仍然 ≤100%)。
  // 判定用"任一计数器 > 0"而不是只看分母: 否则"埋设 0 / 了结 3"这种数据不一致会被兜底悄悄盖住
  // (显示成 0/0), 而不是按 dsh 的要求暴露成异常。
  const 队列埋设 = 取数(指标?.累计埋设);
  const 队列了结 = 取数(指标?.累计了结);
  const 有队列 = 队列埋设 > 0 || 队列了结 > 0;
  const 埋设数 = 有队列 ? 队列埋设 : 当前伏笔.length;
  const 回收数 = 有队列 ? 队列了结 : 当前伏笔.filter(项 => 是了结状态(项?.状态)).length;
  const 回收异常 = 回收数 > 埋设数;
  if (回收异常) {
    console.warn(
      `[剧情导演] 伏笔回收率数据异常: 累计了结 ${回收数} > 累计埋设 ${埋设数}(面板显示异常态, 不夹断也不显示 >100%)`,
    );
  }
  const 伏笔回收率 = 埋设数 > 0 && !回收异常 ? Math.min(1, 回收数 / 埋设数) : -1;

  const 张力历史 = Array.isArray(指标?.张力历史) ? 指标!.张力历史 : [];
  const 张力波形 = 张力历史.map(项 => 取数(项.值));
  // -1 = 未观测, 不参与峰谷(否则"未观测"会被当成 0 拉低谷值、并让面板显示 0)
  const 峰候选 = [取数(累计?.张力峰, 未观测张力), ...章节统计.map(项 => 取数(项.张力峰, 未观测张力)), ...张力波形].filter(值 => 值 >= 0);
  const 谷候选 = [取数(累计?.张力谷, 未观测张力), ...章节统计.map(项 => 取数(项.张力谷, 未观测张力)), ...张力波形].filter(值 => 值 >= 0);
  const 核验总 = 取数(指标?.核验?.总);
  const 核验未执行 = 取数(指标?.核验?.未执行);

  return {
    伏笔回收率,
    伏笔回收率异常: 回收异常,
    张力波形,
    张力峰: 峰候选.length > 0 ? Math.max(...峰候选) : 未观测张力,
    张力谷: 谷候选.length > 0 ? Math.min(...谷候选) : 未观测张力,
    起伏次数: 求和(项 => 项.起伏次数) + 取数(累计?.起伏次数),
    冲突推进数: 求和(项 => 项.冲突推进数) + 取数(累计?.冲突推进数),
    受挫次数: 求和(项 => 项.受挫数) + 取数(累计?.受挫数),
    指令执行率: 核验总 > 0 ? 1 - 核验未执行 / 核验总 : -1,
    明细: {
      埋设数,
      回收数,
      累计埋设: 队列埋设,
      累计了结: 队列了结,
      章节活动埋设: 求和(项 => 项.埋设数) + 取数(累计?.埋设数),
      章节活动回收: 求和(项 => 项.回收数) + 取数(累计?.回收数),
      核验总,
      核验未执行,
      已结算章数: 章节统计.length,
    },
  };
}
