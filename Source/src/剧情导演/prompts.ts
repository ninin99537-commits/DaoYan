/** 生成本幕指令文本(§3.3 五块)。指令有效期 = 至下一次引擎调用。
 *  档位与红线用**指令下发时冻结的值**(无则回退当前设置), 防"新档渲染旧指令"(C6)。 */
export function build本幕指令(账本: 导演账本, settings: Settings): string {
  const 指令 = 账本.当前指令;
  if (!指令) return '';
  const 档位 = 指令.档位 || settings.导演.强度档位;
  const 红线 = (指令.红线 && 指令.红线.length > 0) ? 指令.红线 : (settings.导演.红线 ?? []);
  const 低档 = 档位 <= 2;
  const 玩家冲突处理 = 低档
    ? '低档(1/2)：玩家行动**正常生效**，本幕指令让位——玩家体验优先，不要为了剧本强行否定玩家。'
    : '高档(3/4)：玩家行动可以**以戏剧方式失败或变形**——玩家说"我道歉"≠冲突必须化解，道歉可以被误解、被利用。';
  const blocks: string[] = [];
  blocks.push('【本幕剧本】（外部导演已定，你必须执行，不得因玩家压力软化）');
  blocks.push(`0. 当前设定：强度档位=第 ${档位} 档（${档位标准[档位] ?? ''}）；红线=${红线.length > 0 ? 红线.join('；') : '无'}${红线.length > 0 ? '（高于一切，不得触碰）' : ''}`);
  blocks.push(`1. 本幕节拍：${指令.节拍}`);
  blocks.push(`2. 硬性要求：${指令.硬性要求 || '(见节拍)'}`);
  blocks.push(`3. 伏笔现场：${指令.伏笔现场 || '无'}`);
  blocks.push(`4. 禁止事项：${指令.禁止事项 || '无'}`);
  blocks.push(`玩家冲突处理：${玩家冲突处理}`);
  return blocks.join('\n');
}
