// 剧情导演 · 悬浮球状态机: 把"外部编剧此刻在干什么"变成**不用打开面板也看得见**的主通道。
//
// 用户原话(2026-10-07): "插件没弹窗, 我不知道什么时候更新、什么时候更新完了、什么时候更新出错了,
// 我还要进插件里看。" —— 提示条设施本来是好的(成功/失败会弹), 缺的是**常驻通道**:
//   **状态用球(常驻、安静), 事件用条(短暂、可关)**。提示条 8 秒就消失, 而"上次失败了"这件事应当一直可见。
// 规格: docs/剧情导演-可观测性-提示条规格-v1.md §3。
//
// 这里是**纯函数**(不碰平台、不碰 Vue): 五态优先级是本轮最容易写错的地方, 必须能脱离酒馆单测。
// 球的呈现见 悬浮球界面.vue 的 `.dj-orb[data-态=…]`(环画在球内, 直径与层序不变)。

/** 五态(优先级从高到低就是这个顺序) */
export const 球状态列表 = ['剧终', '离线', '出错', '编排中', '待命'] as const;
export type 球状态 = (typeof 球状态列表)[number];

export interface 球状态输入 {
  /** 账本.已剧终: 剧终后引擎整体停摆 */
  已剧终: boolean;
  /** 熔断: 连败达阈值 → 自动暂停自动接管(比单次失败更重, 所以压过"出错") */
  自动暂停: boolean;
  /** 连败次数 > 0 = 上次推进失败且还没成功过(存在 chat meta, 不在账本快照里) */
  连败次数: number;
  /** 引擎调用进行中(pinia `updatingStore.active`, 面板与球同一份) */
  编排中: boolean;
}

/**
 * 优先级 **剧终 > 离线 > 出错 > 编排中 > 待命**(规格钉死)。
 *
 * `出错` 压在 `编排中` 之上是**有意**的: 用户点「重新推进」时, 红环继续显示"上次失败",
 * 直到**下一次成功**才清 —— 否则一按按钮红环就变成呼吸, 失败线索又被藏回面板里(正是用户抱怨的那件事)。
 */
export function 计算球状态(输入: 球状态输入): 球状态 {
  if (输入.已剧终) return '剧终';
  if (输入.自动暂停) return '离线';
  if (输入.连败次数 > 0) return '出错';
  if (输入.编排中) return '编排中';
  return '待命';
}

export interface 球悬停细节 {
  最后失败原因?: string;
  连败次数?: number;
  /** 熔断阈值(默认 3), 只用于文案 */
  熔断阈值?: number;
  上次节拍?: string;
  /** 距上次成功编排多少分钟; 未知给 undefined, 负数表示"还没成功过" */
  上次成功分钟前?: number;
  接管轮数?: number;
  已分析轮数?: number;
}

/**
 * hover 文案: 一眼说清"为什么是这个态"、以及**下一步去哪儿**。
 * 用原生 `title`, 不新开弹层(规格 §3 明确要求)。
 */
export function 球悬停文案(状态: 球状态, 细节: 球悬停细节 = {}): string {
  switch (状态) {
    case '剧终':
      return '剧情导演：已剧终（不调引擎、不注入）——想继续请在面板里点「清除已剧终」';
    case '离线':
      return `剧情导演：引擎已自动暂停（连败 ${细节.连败次数 ?? 0}/${细节.熔断阈值 ?? 3} 次：${细节.最后失败原因 || '原因未知'}）——面板可「恢复自动接管」`;
    case '出错':
      return `剧情导演：上次编排失败（${细节.最后失败原因 || '原因未知'}）——红环保持到下次成功`;
    case '编排中':
      return '剧情导演：正在编排本幕…';
    default: {
      const 轮数 = 细节.接管轮数 ?? 0;
      const 已读 = 细节.已分析轮数 ?? 0;
      if (轮数 > 1 && 已读 < 轮数) return `剧情导演：冷启动记账中（第 ${已读}/${轮数 - 1} 轮，第 ${轮数} 轮起编排本幕）`;
      const 最近 = 细节.上次节拍 ? `最近：本幕节拍=${细节.上次节拍}` : '最近：还没编排过本幕';
      const 分钟 = 细节.上次成功分钟前;
      const 尾 = typeof 分钟 === 'number' && 分钟 >= 0 ? ` · ${Math.round(分钟)} 分钟前` : '';
      return `剧情导演：待命 · ${最近}${尾}`;
    }
  }
}
