// 剧情导演 · 账本数据: 把引擎输出规范化成账本(四本账增量维护 / 编号签发 / 淘汰 / 张力折算)。
// 纯数据变换, 不碰平台(可脱离酒馆测)。
import { klona } from 'klona';
import { 取层, 规范化条目, 淘汰, 折算张力, 低张力节拍 } from './字段表';
import { 维护指标 } from './指标';
import type { 导演账本, 章回, 伏笔, 冲突, 弧线, 节拍 } from './schema';
import { 节拍列表 } from './schema';
import type { 核验结果 } from './引擎规则';

export interface 应用结果 {
  账本: 导演账本;
  变化: { 伏笔: string[]; 冲突: string[]; 弧线: string[] };
  上一幕节拍: 节拍;
  核验: 核验结果;
}

function 是节拍(x: unknown): x is 节拍 {
  return 节拍列表.includes(x as 节拍);
}

/** 把引擎输出的账本更新合并进旧账本: 编号全局单调递增永不复用; 伏笔内容写下即冻结 */
export function 应用引擎输出(旧: 导演账本, 载荷: any, 楼层: number): 应用结果 {
  const 账本 = klona(旧);
  const 变化: 应用结果['变化'] = { 伏笔: [], 冲突: [], 弧线: [] };

  // 执行核验(缺省视为已执行)——提前算, 冲突对账要用它判"本轮该冲突有没有被顶回"
  const raw核验 = 载荷?.上一幕核验 && typeof 载荷.上一幕核验 === 'object' ? 载荷.上一幕核验 : {};
  const 核验: 核验结果 = {
    已执行: raw核验.已执行 !== false,
    顶回冲突: String(raw核验.顶回冲突 ?? '').trim(),
    说明: String(raw核验.说明 ?? ''),
    主角死亡: !!raw核验.主角死亡,
  };

  // 章回(活跃 ≤1)
  账本.章回 = 载荷?.章回 && typeof 载荷.章回 === 'object' ? 规范化条目<章回>(取层('章回'), 载荷.章回) : null;

  // 伏笔(埋设章由**代码**在签发时填当前章号 —— 指标账依赖它, 见 指标.ts)
  const 当前章号 = Number(账本.章回?.章号) || Number(旧.章回?.章号) || 0;
  const 旧伏笔 = new Map(旧.伏笔.map(item => [item.编号, item]));
  const 旧内容索引 = new Map(旧.伏笔.map(item => [item.内容, item]));
  const 新伏笔: 伏笔[] = [];
  let 下一伏笔编号 = Math.max(1, 旧.下一伏笔编号);
  for (const raw of Array.isArray(载荷?.伏笔) ? 载荷.伏笔 : []) {
    const 规范 = 规范化条目<伏笔>(取层('伏笔'), raw);
    const 声明编号 = Number(raw?.编号) || 0;
    let 旧条: 伏笔 | undefined;
    if (声明编号 > 0) 旧条 = 旧伏笔.get(声明编号);
    if (!旧条 && 规范.内容) 旧条 = 旧内容索引.get(规范.内容);
    if (旧条) {
      // 内容冻结 + 沿用原埋设层/埋设章; 只允许改状态/窗口/关联冲突
      if (旧条.状态 !== 规范.状态) 变化.伏笔.push(`#${旧条.编号} ${旧条.状态}→${规范.状态}`);
      const 合并: 伏笔 = {
        ...规范,
        编号: 旧条.编号,
        内容: 旧条.内容,
        埋设层: 旧条.埋设层,
        埋设章: Number(旧条.埋设章) || 当前章号,
      };
      旧伏笔.delete(旧条.编号);
      新伏笔.push(合并);
    } else {
      const 编号 = 下一伏笔编号++;
      新伏笔.push({ ...规范, 编号, 埋设层: 楼层, 埋设章: 当前章号 });
      变化.伏笔.push(`新增 #${编号} ${规范.内容}`);
    }
  }
  // AI 未带回的既有伏笔: 原样捞回(防换血); 埋设章缺省(旧账本)时回填当前章号
  for (const 剩 of 旧伏笔.values()) {
    if (!新伏笔.some(item => item.编号 === 剩.编号)) 新伏笔.push({ ...剩, 埋设章: Number(剩.埋设章) || 当前章号 });
  }
  账本.伏笔 = 淘汰(新伏笔, 取层('伏笔'));
  账本.下一伏笔编号 = 下一伏笔编号;

  // 冲突(按名对账, 保留连败让步计数)
  const 旧冲突 = new Map(旧.冲突.map(item => [item.名, item]));
  const 新冲突: 冲突[] = [];
  for (const raw of Array.isArray(载荷?.冲突) ? 载荷.冲突 : []) {
    const 规范 = 规范化条目<冲突>(取层('冲突'), raw);
    if (!规范.名) continue;
    const 旧条 = 旧冲突.get(规范.名);
    if (!旧条) 变化.冲突.push(`新增 ${规范.名}`);
    else {
      旧冲突.delete(规范.名);
      if (旧条.阶段 !== 规范.阶段) 变化.冲突.push(`${规范.名} ${旧条.阶段}→${规范.阶段}`);
    }
    新冲突.push({ ...规范, 顶回次数: 核验.顶回冲突 === 规范.名 ? (旧条?.顶回次数 ?? 0) : 0 });
  }
  for (const 剩 of 旧冲突.values()) {
    if (!新冲突.some(item => item.名 === 剩.名)) 新冲突.push(剩);
  }
  账本.冲突 = 淘汰(新冲突, 取层('冲突'));

  // 弧线(按角色对账)
  const 旧弧线 = new Map(旧.弧线.map(item => [item.角色, item]));
  const 新弧线: 弧线[] = [];
  for (const raw of Array.isArray(载荷?.弧线) ? 载荷.弧线 : []) {
    const 规范 = 规范化条目<弧线>(取层('弧线'), raw);
    if (!规范.角色) continue;
    const 旧条 = 旧弧线.get(规范.角色);
    if (旧条) 旧弧线.delete(规范.角色);
    else 变化.弧线.push(`新增 ${规范.角色}`);
    新弧线.push(规范);
  }
  for (const 剩 of 旧弧线.values()) {
    // 老账本(批次一之前)的弧线阶段可能是自由文本 → 这里也过一遍规范化,
    // 让"阶段 === 闭环"的终态判定在本轮就正确(否则写歪的弧线永远淘汰不掉, kilo 声明的限制)
    if (!新弧线.some(item => item.角色 === 剩.角色)) 新弧线.push(规范化条目<弧线>(取层('弧线'), 剩));
  }
  账本.弧线 = 淘汰(新弧线, 取层('弧线'));

  // 上一幕节拍(引擎对刚演完这一幕的归类; 缺省用旧指令节拍)
  const 上一幕节拍: 节拍 = 是节拍(载荷?.上一幕节拍) ? 载荷.上一幕节拍 : (旧.当前指令?.节拍 ?? '阴影');

  // 张力: 代码折算为主, AI 报数仅校正
  const 校正 = typeof 载荷?.张力校正 === 'number' && Number.isFinite(载荷.张力校正) ? 载荷.张力校正 : null;
  账本.张力 = {
    当前: 折算张力(旧.张力.当前, 上一幕节拍, 校正),
    最近节拍: [...旧.张力.最近节拍, 上一幕节拍].slice(-6),
    连续低张力: 低张力节拍.includes(上一幕节拍) ? 旧.张力.连续低张力 + 1 : 0,
    距上次高潮楼层: 上一幕节拍 === '高潮' ? 0 : 旧.张力.距上次高潮楼层 + 1,
  };

  // 执行核验(缺省视为已执行)已在上方提前算出(冲突对账要用)

  // 指标账(K): 累计本轮 → 历史 → 核验累计 → 章节结算(幂等)。纯代码维护, 零 AI 负担。
  账本.指标 = 维护指标({ 旧, 新: 账本, 楼层, 上一幕节拍, 核验, 变化 });

  return { 账本, 变化, 上一幕节拍, 核验 };
}
