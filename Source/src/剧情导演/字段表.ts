/** 把刚演完的节拍折算进张力曲线: 上轮值 + 增量, AI 校正按 30% 权重并入, 钳制 0~10 */
export function 折算张力(上轮: number, 节拍: 节拍, 校正?: number | null): number {
  const base = (Number.isFinite(上轮) ? 上轮 : 0) + (张力增量[节拍] ?? 0);
  const adj = typeof 校正 === 'number' && Number.isFinite(校正) ? (校正 - base) * 0.3 : 0;
  return _.clamp(Math.round(base + adj), 0, 10);
}
