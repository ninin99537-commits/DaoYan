/** 规范化一条条目: 结构字段按上限守卫, 内容字段零截断, 枚举校验并兜底 */
export function 规范化条目<T extends Record<string, any>>(定义: 账本层定义, raw: Record<string, any>): T {
  const out: Record<string, any> = {};
  for (const 字段 of 定义.字段) {
    const value = raw?.[字段.键];
    if (字段.数值) {
      const n = Number(value);
      out[字段.键] = Number.isFinite(n) ? n : 0;
      continue;
    }
    let text = String(value ?? '');
    if (字段.属性 === '结构') {
      text = text.trim();
      if (字段.上限) text = text.slice(0, 字段.上限);
    }
    if (字段.枚举) {
      // 枚举校验: 命中即留; 未命中先按 归一 把老账本的自由文本映射进枚举; 再不行才走兜底
      const 归一后 = 字段.枚举.includes(text) ? text : 字段.归一 ? 字段.归一(text) : '';
      out[字段.键] = 字段.枚举.includes(归一后) ? 归一后 : (字段.兜底 ?? 字段.枚举[0]);
    } else {
      out[字段.键] = text;
    }
  }
  return out as T;
}

/**
 * 淘汰: 终态(已引爆/已消亡/已收档/闭环/已完结)最旧优先; 满额且全进行中时允许临时突破 1 席
 * (绝不静默丢弃新事件); 只有 AI 返回的量远超额(> 容量+1)时才丢最旧的活动项兜底。
 */
export function 淘汰<T extends Record<string, any>>(列表: T[], 定义: 账本层定义): T[] {
  const out = [...列表];
  let i = 0;
  while (out.length > 定义.容量 && i < out.length) {
    if (定义.终态(out[i])) out.splice(i, 1);
    else i++;
  }
  while (out.length > 定义.容量 + 1) out.shift();
  return out;
}

