/**
 * 老账本的弧线阶段是自由文本(批次一之前引擎可以随便写) → 按关键词归一到枚举; 归不了给 '初始'(兜底)。
 * 兜底取 '初始' 而不是 '闭环': 把未知文本判成终态, 会把**还能演的弧线**直接淘汰掉;
 * 而 kilo 提的"写歪 → 永不淘汰"风险, 靠枚举 + 提示词同步就堵住了(新写入不再有自由文本), 不需要靠兜底误杀。
 * 映射规则(顺序即优先级, dsh 2026-10-07 审定):
 *   完成态(闭环|完结|完成|终结|收束|结束|达成|圆满|功成, 且**不带否定词**) → 闭环
 *   蜕变|成长|重生|觉醒 → 蜕变;; 抉择|选择|决断|决心 → 抉择;
 *   挣扎|动摇|痛苦|冲突|抗争 → 挣扎;; 裂缝|裂痕|裂隙|初现 → 裂缝; 其余 → 初始。
 * 否定词守卫: "尚未完成"/"没有闭环" 不算完成态(否则一条还在演的弧线会被误判终结)。
 */
export function 归一弧线阶段(文本: string): string {
  const 值 = String(文本 ?? '').trim();
  if (!值) return '';
  const 带否定 = /未|没|尚未|还没|无法/.test(值);
  if (!带否定 && /闭环|完结|完成|终结|收束|结束|达成|圆满|功成/.test(值)) return '闭环';
  if (/蜕变|成长|重生|觉醒/.test(值)) return '蜕变';
  if (/抉择|选择|决断|决心/.test(值)) return '抉择';
  if (/挣扎|动摇|痛苦|冲突|抗争/.test(值)) return '挣扎';
  if (/裂缝|裂痕|裂隙|初现/.test(值)) return '裂缝';
  return '初始';
}

