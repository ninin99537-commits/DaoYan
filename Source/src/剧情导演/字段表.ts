// ---------------------------------------------------------------------------

export type 字段属性 = '结构' | '内容';

export interface 字段定义 {
  键: string;
  属性: 字段属性;
  /** 结构字段的写入上限(格式守卫); 内容字段没有这一项 = 零截断 */
  上限?: number;
  枚举?: readonly string[];
  兜底?: string;
  /**
   * 老账本迁移用: 值不在枚举内时先按此函数把自由文本归一(返回空串则走 兜底)。
   * 只在"写歪了的历史值"上生效 —— 新写入由提示词钉在枚举内(批次二 弧线终态枚举化)。
   */
  归一?: (文本: string) => string;
  /** 数值型(用 Number 规范化) */
  数值?: boolean;
}

export interface 账本层定义 {
  名: string;
  容量: number;
  /** 名称键: ''=条目无名字(伏笔按编号); 否则是该层用于对账的名字字段 */
  名称键: string;
  字段: 字段定义[];
  /** 终态判定(终态=可淘汰) */
  终态: (条目: Record<string, any>) => boolean;
}

