/** 一套完整的接口配置(当前配置与预设共用同一结构) */
export const ApiConfigSchema = z
  .object({
    地址: z.string().default(''),
    密钥: z.string().default(''),
    模型: z.string().default(''),
    模型列表: z.array(z.string()).default([]),
    流式: z.boolean().default(false),
    温度: z.coerce
      .number()
      .default(0.8)
      .transform(value => _.clamp(value, 0, 2)),
    最大token: z.coerce
      .number()
      .default(60000)
      .transform(value => Math.max(1, Math.min(131072, Math.round(value)))),
  })
  .prefault({});
export type ApiConfig = z.infer<typeof ApiConfigSchema>;

/**
 * E 配置化的**默认值唯一事实源**（dsh 2026-10-07 裁定②）：
 * 设置页默认值（下面的 SettingsSchema）与引擎兜底（引擎规则.ts）都引用这里，
 * 否则"设置默认一改、引擎兜底就漂移"，又变成第二个事实源。
 */
export const 接管轮数默认 = 4;
export const 连续高阈值默认 = 3;
export const 连续低阈值默认 = 3;

export const SettingsSchema = z
  .object({
    /** 启用导演: 关闭后不再调用引擎、不再注入, 已有账本保留 */
    启用导演: z.boolean().default(true),
    接口: ApiConfigSchema,
    /** 多套接口配置预设(名字 → 完整配置) */
    接口预设: z.record(z.string(), ApiConfigSchema).default({}),
    导演: z
      .object({
        自动接管: z.boolean().default(true),
        /**
         * 可观测性(2026-10-07): 提示条档位(取值清单来自 toast.ts, 同一个事实源)。
         * **事件用条、状态用球** —— 选「关闭」只是不出声, 悬浮球仍然反映 编排中/出错/离线/剧终。
         */
        提示条: z.enum(提示档列表).default(提示档默认),
        /** 每 N 轮主AI回复推进一次引擎(1=每轮) */
        更新频率: z.coerce
          .number()
          .default(1)
          .transform(value => Math.max(1, Math.round(value))),
        /** 楼层快照保留份数: 删楼=回退到更早快照(默认 30, 可调 1~100; 每份几 KB~十几 KB, 调大聊天文件变大) */
        快照保留份数: z.coerce
          .number()
          .default(30)
          .transform(value => Math.max(1, Math.min(100, Math.round(value)))),
        /** 戏剧强度档位 1~4(§4): 1 轻松日常 / 2 平稳叙事 / 3 跌宕起伏 / 4 残酷 */
        强度档位: z.coerce
          .number()
          .default(3)
          .transform(value => Math.max(1, Math.min(4, Math.round(value)))),
        /** 接管轮数(E 配置化): 冷启动期只记账不下令, 第 N 轮起注入本幕指令(默认 4) */
        接管轮数: z.coerce
          .number()
          .default(接管轮数默认)
          .transform(value => Math.max(1, Math.min(20, Math.round(value)))),
        /** 张力阈值(E 配置化): 连续 N 幕高张力 → 强制喘息幕(默认 3) */
        连续高阈值: z.coerce
          .number()
          .default(连续高阈值默认)
          .transform(value => Math.max(1, Math.min(10, Math.round(value)))),
        /** 张力阈值(E 配置化): 连续 N 幕低张力 → 安排"山雨欲来"(默认 3) */
        连续低阈值: z.coerce
          .number()
          .default(连续低阈值默认)
          .transform(value => Math.max(1, Math.min(10, Math.round(value)))),
        /** 红线: 用户钉死的不可触碰项, 优先于一切指令与档位 */
        红线: z.array(z.string()).default([]),
        /**
         * 旧的一刀切防剧透开关(v1.1)。规格 A1: **拆成两键之后它只作兼容来源, 不再显示在 UI 上** ——
         * 装载时"新键缺失才用它播种"(见下面 导演 的 transform), 免得用户只关掉一项却被旧值盖回去。
         */
        防剧透: z.boolean().optional(),
        /** 折叠「未引爆伏笔」的内容 —— **只在显示层折叠**, 账本里与发给引擎的内容一条不少 */
        防剧透伏笔: z.boolean().optional(),
        /** 折叠「章回.计划高潮」 */
        防剧透章回: z.boolean().optional(),
        /** 引擎读取最近 N 条 AI 回复(选择发什么, 不是发了再截) */
        读取最近回复数: z.coerce
          .number()
          .default(3)
          .transform(value => Math.max(1, Math.min(20, Math.round(value)))),
        /** 引擎读世界书(与主 AI 相同激活逻辑) */
        读取世界书: z.boolean().default(true),
        读取全局世界书: z.boolean().default(false),
        世界书排除: z.array(z.string()).default([]),
        /** 事实层注入: 把「编剧备忘」写入角色卡主世界书常驻条目 */
        注入世界书条目: z.boolean().default(true),
        // 提示词开关(同族)
        破限: z.boolean().default(false),
        头部填充: z.boolean().default(false),
        头部填充文本: z.string().default(''),
        防截断: z.boolean().default(false),
        预填充: z.boolean().default(false),
      })
      .prefault({})
      /**
       * 防剧透拆两键的**迁移播种**(规格 A1): `新键 ?? 旧键 ?? true`。
       * 新键一旦存在就以新键为准(旧键此后不再有任何影响); 老设置里只有旧键时两个新键都跟着它走。
       * 用 transform 而不是 `.default(true)`, 正是因为要保留"这个键原本缺失"这个信息。
       */
      .transform(d => ({
        ...d,
        防剧透伏笔: d.防剧透伏笔 ?? d.防剧透 ?? true,
        防剧透章回: d.防剧透章回 ?? d.防剧透 ?? true,
      })),
    标签: z
      .object({
        模式: z.enum(['排除', '只读']).default('排除'),
        列表: z.array(z.string()).default(['aftertalk']),
      })
      .prefault({}),
  })
  .prefault({});
export type Settings = z.infer<typeof SettingsSchema>;

