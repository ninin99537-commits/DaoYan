/** 一章的结算统计: 章回转「已完结」时由代码结算一条, 有界 20 章(最旧优先淘汰) */
export interface 章节统计 {
  章号: number;
  /** 本章签发的新伏笔数 */
  埋设数: number;
  /**
   * 本章**了结**（引爆/消亡）的伏笔数 —— **可能含前章埋下的**。
   * 只作"本章活动量"看：**不得用作伏笔回收率的分子/分母**（那会算出 >100%，见 P1 的 111%）。
   * 回收率用队列口径的 `指标.累计了结 / 指标.累计埋设`。
   */
  回收数: number;
  张力峰: number;
  张力谷: number;
  /** 本章张力方向反转次数(波形起伏) */
  起伏次数: number;
  /** 本章冲突阶段推进次数 */
  冲突推进数: number;
  /** 本章「受挫」节拍次数 */
  受挫数: number;
}

/** 指标账: 判据唯一数据源。纯代码维护 —— 提示词**不**要求 AI 输出任何一项 */
export interface 指标账 {
  章节统计: 章节统计[];
  /** 每轮追加的节拍历史(有界 40) */
  节拍历史: { 楼层: number; 节拍: 节拍 }[];
  /** 每轮追加的张力历史(有界 40) */
  张力历史: { 楼层: number; 值: number }[];
  /** 执行核验累计(仅在存在上一幕指令的那些轮次计数) */
  核验: { 总: number; 未执行: number };
  /** 进行中那一章的累计器(章号 0 = 尚无章回); 结算后重置为下一章 */
  本章累计: 章节统计;
  /**
   * **队列口径**的累计埋设数: 每签发一条新伏笔 +1(与 `本章累计.埋设数` 同时加, 但**永不随章节结算清零**)。
   * 与 `累计了结` 配成一对, 只用于算回收率 —— 章节统计那种"按章归属"的数不能做比值(会 >100%)。
   */
  累计埋设: number;
  /** **队列口径**的累计了结数: 某条伏笔**首次**转入 已引爆/已消亡 时 +1, 按编号去重(同一条永不重复计) */
  累计了结: number;
  /** 已计过"了结"的伏笔编号(去重用; 有界 200, 只在写入端裁切) */
  已了结编号: number[];
  /**
   * 剧终那一刻的判据快照(手动全书结算与死亡剧终都写这里)。**写一次、只读不重算** ——
   * 落幕之后账本仍可能因删楼/回退而变动, 成绩单必须钉在"落幕那一刻"(规格 B3)。
   */
  终值: 判据 | null;
}

/** §3 五项判据(由指标账算出, 面板指标卡与测试判据共用) */
export interface 判据 {
  /** 0~1(队列口径: 累计了结/累计埋设); 无样本时 -1 */
  伏笔回收率: number;
  /** 数据异常(累计了结 > 累计埋设): 面板显示显式异常态, **不做静默夹断** */
  伏笔回收率异常: boolean;
  /** 最近张力读数序列(有界 40) */
  张力波形: number[];
  张力峰: number;
  张力谷: number;
  /** 张力方向反转的总次数(由 章节统计 聚合)。结算卡要它, 所以不能只在章节里躺着 */
  起伏次数: number;
  冲突推进数: number;
  受挫次数: number;
  /** 0~1; 无样本时 -1 */
  指令执行率: number;
  明细: {
    /** 回收率的分子/分母(队列口径: 累计了结 / 累计埋设) */
    埋设数: number;
    回收数: number;
    /** 队列口径的原始累计值(便于面板显示"已了结 X / 已埋设 Y") */
    累计埋设: number;
    累计了结: number;
    /** 章节统计口径的"本章活动量"(只做参考, 不做比值) */
    章节活动埋设: number;
    章节活动回收: number;
    核验总: number;
    核验未执行: number;
    已结算章数: number;
  };
}

/** 剧情账本本体(整体写入楼层快照) */
export interface 导演账本 {
  版本: number;
  章回: 章回 | null;
  伏笔: 伏笔[];
  冲突: 冲突[];
  弧线: 弧线[];
  当前指令: 本幕指令 | null;
  张力: 张力读数;
  /** 伏笔编号发号器: 只增不减, 永不复用 */
  下一伏笔编号: number;
  /** 指令编号发号器 */
  下一指令编号: number;
  /** 已分析轮数(冷启动判定用: 前 3 轮只记账不下令, 第 4 轮起注入指令) */
  已分析轮数: number;
  /** 已剧终(剧终结算后自动路径整体跳过: 不调引擎、不注入)。
   * 双写: 账本 + 聊天变量 meta —— 账本会随快照回退/清空, meta 不会, 故以两者之或为准 */
  已剧终: boolean;
  /**
   * 手动全书结算的**第一段**(规格 B2): 用户点「做全书结算」置 true → 之后每道指令都编排为收束幕,
   * 直到「确认剧终」(落定剧终会清它)或「清除已剧终」(解除剧终也一并清)。
   * **收官请求 ≠ 已剧终**: 期间引擎照常推进、账本照常更新, 只有用户拍板落幕才停摆。
   */
  收官请求: boolean;
  /** 指标账(§3 判据的可算数据; 纯代码维护, 见 指标.ts) */
  指标: 指标账;
  /** 主角死亡待抉择(引擎检测到死亡→true; 用户三选一后由下一轮引擎消费并清回 false) */
  待决死亡: boolean;
  /** 主角死亡后的当场抉择(空=未抉择; 用户选后交给下一轮引擎消费, 消费后清回 '') */
  死亡抉择: 死亡抉择;
  统计: { 引擎调用次数: number; 最后调用: number };
  /** 快照锚定楼层(-1=无快照) */
  锚点楼层: number;
  /** 已推进到哪条楼层 */
  处理到楼层: number;
  /** 清空层(来自聊天变量) */
  清空层: number;
}

