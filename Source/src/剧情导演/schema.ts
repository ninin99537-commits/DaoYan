/** 节拍枚举(冻结于 字段表.ts, 也是代码折算张力的输入) */
export type 节拍 = '受挫' | '小胜' | '阴影' | '反转' | '兑现伏笔' | '高潮' | '余波';
export type 伏笔状态 = '埋下' | '潜伏' | '发酵' | '已引爆' | '已消亡';
export type 冲突阶段 = '铺垫' | '升级' | '僵持' | '决战' | '收束' | '已收档';
export type 章回进度 = '铺垫' | '推进' | '收束' | '已完结';
export type 死亡抉择 = '视角转移' | '世界观内复活' | '剧终结算' | '';

/** 主线章回: 一段有既定汇合点(高潮事件)的弧 */
export interface 章回 {
  章号: number;
  主题: string;
  计划高潮: string;
  进度: 章回进度;
}

/** 伏笔: 埋下后延迟兑现的剧情线头。内容冻结, 编号全局单调递增永不复用 */
export interface 伏笔 {
  编号: number;
  内容: string;
  /** 埋设层(楼层号, 由代码补) */
  埋设层: number;
  /** 埋设章(章号, 由**代码**在签发时填当前章号; 旧账本读到 0 时回填当前章号) —— 指标账用, AI 不输出 */
  埋设章: number;
  状态: 伏笔状态;
  /** 预定回收窗口(以章号锚定, 如"第3章收束前") */
  回收窗口: string;
  关联冲突: string;
}

/** 冲突: 有赌注的对抗 */
export interface 冲突 {
  名: string;
  对立面: string;
  赌注: string;
  强度: number;
  阶段: 冲突阶段;
  下一步: string;
  /** 连败让步计数: 同一冲突连续 2 次玩家被顶回后, 第 3 次让玩家赢 */
  顶回次数: number;
}

/**
 * 弧线阶段(固定枚举 —— 批次二「弧线终态枚举化」):
 * 旧实现靠"文本等于闭环"判淘汰, 引擎把阶段写成自由文本(如"接近闭环")就**永不淘汰**。
 * 现在枚举是唯一合法取值集合, 提示词同步(见 prompts.ts), 老账本自由文本由 字段表.归一弧线阶段 映射。
 */
export const 弧线阶段列表 = ['初始', '裂缝', '挣扎', '抉择', '蜕变', '闭环'] as const;
export type 弧线阶段 = (typeof 弧线阶段列表)[number];

/** 角色弧线: 由缺口驱动的长线成长轨迹 */
export interface 弧线 {
  角色: string;
  缺口: string;
  阶段: 弧线阶段;
  下一步契机: string;
}

/** 已下发的本幕指令(快照是它唯一的持久位置——执行核验的比对对象) */
export interface 本幕指令 {
  /** 指令序号(也是版本号) */
  编号: number;
  节拍: 节拍;
  硬性要求: string;
  伏笔现场: string;
  禁止事项: string;
  /** 由哪一楼层的引擎调用生成 */
  生成楼层: number;
  /** 核验未执行导致的升级次数(封顶 2) */
  核验升级次数: number;
  /** 用户跳过本幕 */
  已跳过: boolean;
  /** 代码结构规则对指令的干预说明(张力曲线/契诃夫之枪/收束调度/余波/核验升级/连败让步) */
  代码调整: string[];
  /** 下发时的强度档位(冻结进快照, 注入用冻结值, 防"新档渲染旧指令") */
  档位: number;
  /** 下发时的红线(冻结进快照) */
  红线: string[];
}

/** 张力读数(代码折算为主, AI 报数仅校正) */
export interface 张力读数 {
  当前: number;
  距上次高潮楼层: number;
  连续低张力: number;
  最近节拍: 节拍[];
}

