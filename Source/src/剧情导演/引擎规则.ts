// 剧情导演 · 导演引擎的代码层结构规则(§3.2 五条) + 本幕指令装配。
// 规则不靠模型自觉: 张力曲线 / 契诃夫之枪 / 收束调度 / 高潮后代价 / 执行核验 + 连败让步。
// 纯函数, 不碰平台。
import type { 导演账本, 本幕指令, 节拍 } from './schema';
import { 节拍列表, 接管轮数默认, 连续高阈值默认, 连续低阈值默认 } from './schema';
import { 高张力节拍 } from './字段表';

export interface 核验结果 {
  已执行: boolean;
  顶回冲突: string;
  说明: string;
  主角死亡: boolean;
}

const 升级封顶 = 2;

export const 档位标准: Record<number, string> = {
  1: '轻松日常——小波折，无实质损失',
  2: '平稳叙事——有起伏，主角基本赢',
  3: '跌宕起伏——三幕波形，挫折-反转交替，配角可死、可失',
  4: '残酷——主角可惨败，重要之物可永久失去，主线可失败',
};

function 尾部连续(节拍序列: 节拍[], 集合: 节拍[]): number {
  let n = 0;
  for (let i = 节拍序列.length - 1; i >= 0 && 集合.includes(节拍序列[i]); i--) n++;
  return n;
}

export interface 构造参数 {
  旧指令: 本幕指令 | null;
  下一幕: any;
  账本: 导演账本;
  核验: 核验结果;
  档位: number;
  红线: string[];
  楼层: number;
  /** 死亡抉择未定/群聊等导致暂停注入 */
  暂停注入: boolean;
  /**
   * E 配置化: 张力阈值(连续高/低)。生产路径由 settings 传入(schema.ts 默认 3/3);
   * 缺省(直接调本函数的老用例)时退回 3 —— 只是防御性兜底, 不改变张力曲线行为。
   */
  阈值?: { 高: number; 低: number };
  /** E 配置化: 冷启动接管轮数。生产路径由 settings 传入(schema.ts 默认 4) */
  接管轮数?: number;
}

export interface 构造结果 {
  指令: 本幕指令 | null;
  调整: string[];
  顶回更新: Record<string, number>;
}

/** 装配本幕指令: 先跑代码层结构规则调整节拍, 再把档位/红线/核验/连败让步写进硬性要求 */
export function 构造本幕指令(参数: 构造参数): 构造结果 {
  const { 旧指令, 下一幕, 账本, 核验, 档位, 红线, 楼层, 暂停注入, 阈值, 接管轮数 } = 参数;
  const 调整: string[] = [];
  const 顶回更新: Record<string, number> = {};
  // E 配置化: 阈值/接管轮数由 settings 传入; 老调用点缺字段时退回**默认常量**(schema 里的事实源, 不再写字面量)
  const 高阈 = Number.isFinite(Number(阈值?.高)) ? Number(阈值?.高) : 连续高阈值默认;
  const 低阈 = Number.isFinite(Number(阈值?.低)) ? Number(阈值?.低) : 连续低阈值默认;
  const 轮数 = Number.isFinite(Number(接管轮数)) ? Number(接管轮数) : 接管轮数默认;

  // 连败自动让步(用户决策 Q3): 同一冲突连续 2 次顶回 → 第 3 次必须让玩家赢
  let 让步冲突 = '';
  if (核验.顶回冲突) {
    const 冲突条 = 账本.冲突.find(item => item.名 === 核验.顶回冲突);
    if (冲突条) {
      const 新次数 = (冲突条.顶回次数 ?? 0) + 1;
      if (新次数 >= 2) {
        让步冲突 = 冲突条.名;
        顶回更新[冲突条.名] = 0;
        调整.push(`连败让步：冲突「${冲突条.名}」连续 2 次顶回，本轮让玩家赢`);
      } else {
        顶回更新[冲突条.名] = 新次数;
      }
    }
  }

  if (暂停注入) return { 指令: null, 调整, 顶回更新 };
  // 冷启动: 前几轮只记账不下令, 第 轮数 轮起注入指令(轮数来自设置, E 配置化)
  if (账本.已分析轮数 < 轮数) return { 指令: null, 调整, 顶回更新 };

  // ---- 手动全书结算 · 收束幕(规格 B2 第一段) ----
  // 用户拍板要落幕, 这一道指令就**不再走常规五条规则**(常规规则会把戏往"下一段剧情"引, 收官要的是收尾)。
  // 节拍取 `兑现伏笔`(dsh 批准): 收官幕的**任务**是"把该了结的了结", 正是回收语义;
  //   不取 `余波` —— 它是"高潮之后的降温幕", 拿它当全书最后一幕会先泄气, 还会跟"高潮后必有代价"撞车。
  // "不总结、不升华、留余味"写进硬性要求: **余味由文字承担, 不靠节拍降调**。
  // 幂等由 账本.收官请求 保证(请求收官 只认第一次), 所以这里每轮最多产出一道收束幕指令。
  if (账本.收官请求) {
    const 待了结 = 账本.伏笔.filter(项 => 项.状态 !== '已引爆' && 项.状态 !== '已消亡');
    const 未收档 = 账本.冲突.filter(项 => 项.阶段 !== '已收档');
    调整.push(`全书结算：用户已请求收官（待了结伏笔 ${待了结.length} 条 / 未收档冲突 ${未收档.length} 个），本幕编排为收束幕`);
    const 收束要求 = [
      // 让步不属于"常规五条规则", 而是玩家体验的独立保护(同冲突连续 2 次顶回 → 本轮必须让玩家赢)。
      // 收官幕一样受它管: 收尾可以悲壮, 但不该在这一幕额外踩玩家一脚。
      ...(让步冲突 ? [`【连败让步】冲突「${让步冲突}」本轮必须让玩家赢（收官幕也不例外）。`] : []),
      '【全书收官 · 本轮必须落实】',
      待了结.length
        ? `1）优先把还没了结的伏笔了结：${待了结.map(项 => `#${项.编号}「${项.内容}」`).join('、')}。兑现、消亡、被主动放弃都算"有了结"；**收不了的明确留白, 不许为了圆满硬塞回收**（硬塞会把前面攒的可信度赔掉）。**不要再开新伏笔。**`
        : '1）已无待了结的伏笔：不再新增任何线头, 把已有的画面收紧。',
      未收档.length
        ? `2）把主线冲突推到终局：${未收档.map(项 => `「${项.名}」(赌注：${项.赌注 || '—'})`).join('、')}——给出胜/败/代价的明确结局, 不许悬着。`
        : '2）冲突均已收档：给结局一个落点即可, 不新起冲突。',
      '3）收尾**不总结、不升华、不旁白点评意义**：让画面与动作承担结局, 禁止"从此以后/多年以后回望"式的陈词。',
      '4）这是最后一幕：落幕镜头要在故事**内部**自然停下（一个动作、一句话、一个画面就够）, 不要跳出去向读者告别。',
    ];
    const 指令: 本幕指令 = {
      编号: Math.max(1, 账本.下一指令编号),
      节拍: '兑现伏笔',
      硬性要求: 收束要求.join('\n'),
      伏笔现场: String(下一幕?.伏笔现场 ?? '').trim(),
      禁止事项: '不新增伏笔、不硬塞回收、不总结升华、不向读者告别、不让冲突悬着。',
      生成楼层: 楼层,
      核验升级次数: 0,
      已跳过: false,
      代码调整: [...调整],
      档位,
      红线: [...红线],
    };
    return { 指令, 调整, 顶回更新 };
  }

  const raw节拍 = 下一幕?.节拍;
  let 节拍: 节拍 = 节拍列表.includes(raw节拍) ? raw节拍 : '阴影';

  // rule 1 张力曲线
  const 连续高 = 尾部连续(账本.张力.最近节拍, 高张力节拍);
  const 连续低 = 账本.张力.连续低张力;
  if (连续高 >= 高阈 && 节拍 !== '余波') {
    节拍 = '余波';
    调整.push(`张力曲线：连续 ${连续高} 幕高张力，强制安排喘息幕`);
  } else if (连续低 >= 低阈 && 节拍 !== '阴影') {
    节拍 = '阴影';
    调整.push(`张力曲线：连续 ${连续低} 幕低张力，安排"山雨欲来"（静中必须埋险）`);
  }

  // rule 4 高潮后必有代价(仅档 3/4)
  if (档位 >= 3) {
    const 最近 = 账本.张力.最近节拍[账本.张力.最近节拍.length - 1];
    if (最近 === '高潮' && 节拍 !== '余波') {
      节拍 = '余波';
      调整.push('高潮后必有代价：安排"战后余波"幕');
    }
  }

  // rule 2/3 契诃夫之枪 + 收束调度: 章回逼近收束 或 伏笔逾期(回收窗口章号已到) → 优先"兑现伏笔"
  const 章回 = 账本.章回;
  if (章回 && 节拍 !== '兑现伏笔' && 节拍 !== '高潮' && 节拍 !== '余波') {
    const 可回收 = 账本.伏笔.find(item => item.状态 === '发酵' || item.状态 === '潜伏');
    if (章回.进度 === '收束' && 可回收) {
      节拍 = '兑现伏笔';
      调整.push(`收束调度：章回逼近收束，优先回收伏笔 #${可回收.编号}`);
    } else {
      // 逾期判定: 解析"预定回收窗口"里的章号(如"第3章收束前"), 当前章号 ≥ 窗口章号且未引爆/消亡
      const 逾期 = 账本.伏笔.find(item => {
        if (item.状态 === '已引爆' || item.状态 === '已消亡') return false;
        const m = String(item.回收窗口 ?? '').match(/第\s*(\d+)\s*章/);
        return !!m && 章回.章号 >= Number(m[1]);
      });
      if (逾期) {
        节拍 = '兑现伏笔';
        调整.push(`契诃夫之枪：伏笔 #${逾期.编号} 已过回收窗口，优先回收`);
      }
    }
  }

  // rule 5 执行核验: 未执行 → 升级(封顶 2, 不越档); 已执行 → 复位
  let 核验升级次数 = 旧指令?.核验升级次数 ?? 0;
  const 块: string[] = [];
  if (!核验.已执行 && 核验升级次数 < 升级封顶) {
    核验升级次数 += 1;
    块.push(`【升级·上一幕未被真正执行】以更明确、更强的方式要求，务必落实；**升级后的要求不得超越当前强度档位与红线**：`);
    调整.push(`执行核验：上一幕未执行，升级强度（第 ${核验升级次数}/${升级封顶} 次）`);
  } else if (核验.已执行) {
    核验升级次数 = 0;
  }

  // 装配硬性要求(让步/升级在最前, AI 要求居中, 代码调整殿后);
  // 强度档位与红线由「指令文本」builder 在"0. 当前设定"里统一渲染, 这里不重复。
  const 头: string[] = [];
  if (让步冲突) 头.push(`【连败让步】冲突「${让步冲突}」本轮必须让玩家赢（玩家体验优先）。`);
  const ai硬性 = String(下一幕?.硬性要求 ?? '').trim();
  const 尾 = 调整.map(item => `（代码规则）${item}`);

  const 指令: 本幕指令 = {
    编号: Math.max(1, 账本.下一指令编号),
    节拍,
    硬性要求: [...头, ...块, ...(ai硬性 ? [ai硬性] : []), ...尾].join('\n'),
    伏笔现场: String(下一幕?.伏笔现场 ?? '').trim(),
    禁止事项: String(下一幕?.禁止事项 ?? '').trim(),
    生成楼层: 楼层,
    核验升级次数,
    已跳过: false,
    代码调整: 调整,
    档位,
    红线: [...红线],
  };
  return { 指令, 调整, 顶回更新 };
}

/** 跳过本幕: 作废当前指令(下一幕重新生成), 并**重置核验升级计数**(D2/G: 跳过本幕重置) */
export function 跳过本幕(账本: 导演账本): void {
  if (!账本.当前指令) return;
  账本.当前指令.已跳过 = true;
  账本.当前指令.核验升级次数 = 0;
}
