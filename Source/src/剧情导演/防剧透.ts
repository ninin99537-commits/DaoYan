// 剧情导演 · 防剧透(纯显示层): 折叠 = "默认盖住 + 点一下临时揭开", **绝不是"删掉数据"**。
//
// 用户抱怨(2026-10-07): 「伏笔账看不到内容, 不能弄个设置吗?」 —— v1.1 只有一个一刀切开关,
// 想确认某一条就得把整本摊开, 反而更剧透。规格 A 的修法:
//   ① 拆两键(`防剧透伏笔` / `防剧透章回`, 各自独立);
//   ② **整行可点**, 点一下只揭开**被点的那一条**, 再点收回;
//   ③ 展开态**只在内存**(切页签/刷新/换聊天回到折叠) —— 防剧透仍是默认行为。
// 零截断红线: 这里的判断**只决定渲染哪段文案**; 账本数据与发往引擎的内容一条都不许少。
// 规格: docs/剧情导演-防剧透与手动结算-规格-v1.md §二
import type { 伏笔状态 } from './schema';

export interface 防剧透开关 {
  防剧透伏笔: boolean;
  防剧透章回: boolean;
}

/** 已引爆的伏笔本身就是结局揭晓, 没什么可防的(与 v1.1 行为一致) */
export function 伏笔受管(开关: 防剧透开关, 状态: 伏笔状态 | string): boolean {
  return 开关.防剧透伏笔 && 状态 !== '已引爆';
}

/** 没有"计划高潮"文本就没有可泄的内容 —— 不给它挂一个点了没反应的假按钮 */
export function 章回受管(开关: 防剧透开关, 计划高潮: string | null | undefined): boolean {
  return 开关.防剧透章回 && String(计划高潮 ?? '').trim() !== '';
}

/** 揭开状态按"哪一条"记: 伏笔按编号, 章回计划只有一条 */
export const 伏笔键 = (编号: number): string => `伏#${编号}`;
export const 章回键 = '章回#计划高潮';

/** 折叠中 = 受防剧透管 且 还没被点开 */
export function 折叠中(受管: boolean, 已揭开: Set<string>, 键: string): boolean {
  return 受管 && !已揭开.has(键);
}

/**
 * 点一下: **只**切换这一条。返回新集合(调用方整个替换, 好让 Vue 感知变化),
 * 并且**不落盘** —— 这是"临时揭示"的全部生命周期。
 */
export function 切换揭开(已揭开: Set<string>, 键: string): Set<string> {
  const 下一个 = new Set(已揭开);
  if (下一个.has(键)) 下一个.delete(键);
  else 下一个.add(键);
  return 下一个;
}

export function 折叠文案(哪种: '伏笔' | '章回'): string {
  return 哪种 === '伏笔' ? '（防剧透已折叠内容）' : '（防剧透已折叠）';
}

/** title 提示: 说清"这是临时的、不写盘"(用户最容易担心的是"我点开会不会被记住/剧透给别人") */
export function 揭开提示(当前折叠: boolean): string {
  return 当前折叠 ? '点击临时揭示（不写盘，切页签或刷新即收回）' : '点击收回（防剧透是默认行为）';
}
