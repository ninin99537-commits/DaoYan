// 剧情导演 · 账本变更: 视图改完账本后要走的副作用集(候选二收口)。
// ---------------------------------------------------------------------------
// 面板上几乎每个"修账本"的动作都跟着同一串副作用: 落盘 → (可选)重写「编剧备忘」→
// (可选)生成前重注本幕指令。以前这条链在 悬浮球界面.vue 里手抄了 8 处, 顺序/开关/
// 暂停标志各写各的 —— 改一处要改八处, 漏一处就静默不同步。
//
// 现在收在这里: 视图只声明"这次变更要不要重写备忘 / 要不要重注指令", 顺序与调用细节
// 由本 module 负责。**特例不走这里** —— 剧终/清剧终还要写 chat meta、总开关要撤注入、
// 清空要重载 store, 它们在 悬浮球界面.vue 里各自保留(见那几处注释)。
//
// 它不碰 Vue: 账本与设置都由调用方传入, 平台能力走 注入/快照 各自的接缝, 可脱界面单测。
import { saveData } from './快照';
import { renew本幕指令, sync编剧备忘 } from './注入';
import type { 导演账本, Settings } from './schema';

export interface 变更副作用 {
  /** 重写「编剧备忘」世界书条目: 传"要不要写"(通常 = 设置.导演.注入世界书条目); 不传 = 不动世界书 */
  重写备忘?: boolean;
  /** 生成前重注本幕指令: 传"暂停注入"标志(死亡待决/群聊 = true); 不传 = 不动注入 */
  重注本幕?: boolean;
}

/**
 * 视图改完账本后统一走的副作用链: 先落盘, 再按需重写备忘、重注本幕指令。
 *
 * 顺序刻意固定为 落盘 → 备忘 → 重注: 备忘与指令都以**改完的账本**为准, 落盘失败也照样
 * 刷新世界书/注入(内存里已生效, 只是删楼回退会丢 —— 与原实现一致)。
 *
 * @returns 落盘是否成功
 */
export function 提交账本变更(账本: 导演账本, 设置: Settings, 副作用: 变更副作用 = {}): boolean {
  const 落盘 = saveData(账本);
  // sync编剧备忘 是 async 但内部整段 try/catch(永不 reject), 照原样即发即忘, 不阻塞视图
  if (副作用.重写备忘 !== undefined) void sync编剧备忘(账本, 副作用.重写备忘, 设置);
  if (副作用.重注本幕 !== undefined) renew本幕指令(账本, 设置, 副作用.重注本幕);
  return 落盘;
}